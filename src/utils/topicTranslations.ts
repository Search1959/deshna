// Normalize string for fuzzy lookup
function normalizeKey(str: string): string {
  if (!str) return '';
  return str
    .replace(/[’‘`]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

// Build normalized topic lookup index
const NORMALIZED_TOPIC_LOOKUP: Map<string, TranslatedTopicData> = new Map();
for (const [key, data] of Object.entries(EXACT_TOPIC_TRANSLATIONS)) {
  NORMALIZED_TOPIC_LOOKUP.set(normalizeKey(key), data);
}

